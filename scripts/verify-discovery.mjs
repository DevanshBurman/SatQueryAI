import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'

const url = process.env.VERIFY_URL || 'http://127.0.0.1:5173/'
await fs.mkdir('test-results', { recursive: true })
const browser = await chromium.launch({ headless: true, channel: 'msedge' })
try {
  for (const [width,height] of [[1280,720],[1366,768],[1600,900],[1024,768]]) {
    const page = await browser.newPage({ viewport: {width,height}, deviceScaleFactor: 1 })
    const errors = [], requests = []
    page.on('pageerror', error => errors.push(error.message))
    // Controlled API responses test UI contracts, not live provider availability.
    await page.route('**/api/health', route => route.fulfill({json:{status:'ok',service:'fixture',rasterio:'test'}}))
    await page.route('**/api/catalog/search', route => {
      requests.push(route.request().postDataJSON())
      return route.fulfill({json:{live:true,provider:'test fixture',scenes:[]}})
    })
    await page.goto(url)
    await page.getByRole('button',{name:'Open workspace',exact:true}).first().click()
    await page.locator('.project-tabs').getByRole('button',{name:'Data',exact:true}).click()
    await page.getByRole('heading',{name:'Discover imagery'}).waitFor()
    await page.waitForFunction(() => !document.querySelector('.discovery-search').disabled)
    assert.equal(await page.locator('.imagery-overlay').count(),0)
    assert.equal(await page.locator('.discovery-inspector').count(),0)
    assert.equal(await page.getByRole('button',{name:'Continue',exact:true}).isDisabled(),true)
    const layout = await page.evaluate(() => ({overflow:document.documentElement.scrollWidth>innerWidth, canvas:document.querySelector('.discovery-canvas').getBoundingClientRect().width, footer:document.querySelector('.discovery-attach').getBoundingClientRect().bottom}))
    assert.equal(layout.overflow,false)
    assert.ok(layout.canvas > width * .5)
    assert.ok((await page.locator('.discovery-map').boundingBox()).height > height * .7, 'Map must have visible height')
    assert.ok(layout.footer <= height)
    await page.screenshot({path:`test-results/discovery-empty-${width}.png`})
    await page.getByRole('button',{name:'Use example data'}).click()
    await page.getByRole('button',{name:'Display options'}).click()
    await page.getByRole('slider',{name:'Footprint opacity'}).fill('45')
    await page.getByRole('checkbox',{name:'Scene footprint'}).uncheck()
    await page.getByRole('checkbox',{name:'Scene footprint'}).check()
    await page.getByRole('button',{name:'Use observation',exact:true}).click()
    await page.getByRole('button',{name:'Select Sentinel-1 · example 2024-08-04',exact:true}).click()
    assert.equal(await page.getByText('2 selected',{exact:true}).count(),1)
    await page.screenshot({path:`test-results/discovery-selected-${width}.png`})
    await page.getByRole('button',{name:'Continue',exact:true}).click()
    await page.getByRole('heading',{name:'Choose an analysis'}).waitFor()
    await page.getByRole('heading',{name:'Sentinel-1 · example',exact:true}).waitFor()
    await page.locator('.project-tabs').getByRole('button',{name:'Data',exact:true}).click()
    await page.waitForFunction(() => !document.querySelector('.discovery-search').disabled)
    await page.getByRole('button',{name:'Dates & filters'}).click()
    await page.getByLabel('From',{exact:true}).fill('2024-08-01')
    await page.getByLabel('To',{exact:true}).fill('2024-08-20')
    await page.getByRole('button',{name:'Radar · SAR',exact:true}).click()
    await page.getByRole('textbox',{name:'Find coordinates'}).fill('91, 200')
    await page.getByRole('button',{name:'Go to location'}).click()
    await page.getByText(/Enter latitude, longitude/).waitFor()
    await page.getByRole('textbox',{name:'Find coordinates'}).fill('19.07, 72.87')
    await page.getByRole('button',{name:'Go to location'}).click()
    await page.waitForTimeout(2200)
    await page.getByRole('button',{name:'Search this map area'}).click()
    await page.getByText(/No observations found/).waitFor()
    assert.equal(requests[0].date_from,'2024-08-01')
    assert.equal(requests[0].date_to,'2024-08-20')
    assert.deepEqual(requests[0].sources,['sentinel-1-grd'])
    assert.ok(requests[0].bbox[0]<72.87 && requests[0].bbox[2]>72.87)
    await page.unroute('**/api/catalog/search')
    await page.route('**/api/catalog/search',route=>route.fulfill({json:{live:false,provider:'fallback',scenes:[]}}))
    await page.getByRole('button',{name:'Search this map area'}).click()
    await page.getByText(/Live catalogue is unavailable/).waitFor()
    assert.equal(await page.locator('.discovery-scene').count(),0,'No silent fallback data')
    await page.getByRole('button',{name:'Back to analysis',exact:true}).click()
    await page.getByRole('heading',{name:'Sentinel-1 · example',exact:true}).waitFor()
    assert.deepEqual(errors,[])
    console.log(`PASS ${width}x${height}: layout, map, selection, display, return, coordinates, request filters, empty/error states; API fixture`)
    await page.close()
  }
} finally { await browser.close() }
